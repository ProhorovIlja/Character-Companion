import dev.caicompanion.app.LorebookPolicy as P
import dev.caicompanion.app.LorebookEditor as E

fun verifyLorebookEditor() {
    val gate = P.Entry("Gate", listOf("guard", "city"), "Moonlit street")
    val cafe = P.Entry("Café", listOf("coffee"), "A quiet place")
    val bad = P.Entry("Guard", listOf("guard", " GUARD "), "At the gate")
    val book = P.Book("City", "Night", listOf(gate, cafe, bad), true, 2)
    check(E.search(book, "", false) == listOf(0, 1, 2))
    check(E.search(book, "GUARD moonlit", false) == listOf(0))
    check(E.search(book, "CAFÉ", false) == listOf(1))
    check(E.search(book, "quiet coffee", false) == listOf(1))
    check(E.search(book, "gate", true) == listOf(2))
    check(E.search(book, "missing", false).isEmpty())
    check(E.review(bad) && !E.review(gate))
    check(E.review(gate.copy(keys = emptyList())))
    check(E.review(gate.copy(keys = List(9) { it.toString() })))
    check(E.replace(book, 1, gate)!!.entries == listOf(gate, gate, bad))
    check(E.replace(book, null, cafe)!!.entries.last() == cafe)
    check(E.replace(book, -1, gate) == null)
    check(E.replace(book, 3, gate) == null)
    check(E.replace(book, null, gate.copy(content = "x".repeat(100001))) == null)
    check(E.replace(book.copy(entries = List(1000) { gate }), null, gate) == null)
    check(E.remove(book, 1)!!.entries == listOf(gate, bad))
    check(E.remove(book.copy(entries = listOf(gate)), 0) == null)
    check(E.remove(book, -1) == null)
    check(E.metadata(book, "New", "World")!!.let { it.name == "New" && it.conversionLoss && it.skippedDisabled == 2 })
    check(E.metadata(book, "x".repeat(513), "") == null)
    check(E.keywords(" a,b\n \n café \r\n😀") == listOf("a,b", "café", "😀"))
    check(E.keywords(" ").orEmpty().isEmpty())
    check(E.keywords("x".repeat(513)) == null)
    check(E.keywords(List(257) { "key" }.joinToString("\n")) == null)
    check(book.entries == listOf(gate, cafe, bad))
    println("LorebookEditor: 25 checks passed")
}
